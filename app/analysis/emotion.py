def analyze_emotion_2d(text: str) -> tuple[float, float, str]:
    """Russell 二维情感分析——返回 (valence, arousal, category)。

    valence ∈ [-1, +1]，arousal ∈ [0, 1]。
    category 保持向后兼容：positive / negative / neutral / intimate。
    """
    if not text:
        return (0.0, 0.0, "neutral")

    # ── 亲密词优先 ──
    for w in INTIMATE_WORDS:
        if w in text:
            coords = _VALENCE_AROUSAL_MAP.get(w)
            if coords:
                return (*coords, "intimate")

    # ── 收集所有命中词的坐标 ──
    vals, aros = [], []
    for w, (v, a) in _VALENCE_AROUSAL_MAP.items():
        if w in text:
            vals.append(v)
            aros.append(a)

    if not vals:
        return (0.0, 0.0, "neutral")

    avg_v = sum(vals) / len(vals)
    avg_a = sum(aros) / len(aros)

    # ── 让步句检测：但是/可是/不过 后情绪优先 ──
    # 后半句权重高；前后情绪方向相反时进一步增强后半句主导权
    if any(c in text for c in ("但是", "可是", "不过", "然而", "但却", "只是")):
        for c in ("但是", "可是", "不过", "然而", "但却", "只是"):
            idx = text.find(c)
            if idx != -1:
                after = text[idx + len(c):]
                after_v, after_a, _ = analyze_emotion_2d(after)
                if after_v != 0.0 or after_a != 0.0:
                    if (after_v < 0 and avg_v > 0) or (after_v > 0 and avg_v < 0):
                        # 前后情绪方向相反 → 让步后句主导
                        avg_v = avg_v * 0.15 + after_v * 0.85
                        avg_a = avg_a * 0.15 + after_a * 0.85
                    else:
                        avg_v = avg_v * 0.3 + after_v * 0.7
                        avg_a = avg_a * 0.3 + after_a * 0.7
                break

    # ── 分类 ──
    if avg_v >= 0.2:
        category = "positive"
    elif avg_v <= -0.2:
        category = "negative"
    else:
        category = "neutral"

    return (round(avg_v, 3), round(avg_a, 3), category)


def analyze_emotion(text: str) -> str:
    """保持向后兼容——返回离散情绪标签。

    内部委托给 analyze_emotion_2d()，返回 category 字符串。
    所有现有调用方不受影响。
    """
    _, _, cat = analyze_emotion_2d(text)
    return cat


def resolve_emotion_category(meta: dict) -> str:
    """从 metadata 读取情绪类别，兼容新旧两种格式。

    新格式：emotion_valence 是浮点坐标，emotion_valence_bin 是离散标签。
    旧格式：emotion_valence 是字符串 "positive"/"negative" 等。
    优先读 emotion_valence_bin，fallback 兼容旧格式。
    """
    # 优先读 bin（新格式明确标签）
    bin_val = meta.get("emotion_valence_bin", "")
    if bin_val in ("positive", "negative", "neutral", "intimate"):
        return bin_val

    # fallback: emotion_valence 可能是旧字符串，也可能是新浮点
    ev = meta.get("emotion_valence", "neutral")
    if isinstance(ev, (int, float)):
        if ev >= 0.2:
            return "positive"
        elif ev <= -0.2:
            return "negative"
        else:
            return "neutral"
    if isinstance(ev, str) and ev:
        return ev if ev in ("positive", "negative", "neutral", "intimate") else "neutral"
    return "neutral"
